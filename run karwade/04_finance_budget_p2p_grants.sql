-- ============================================================
-- 1. PURCHASE INDENTS (Department purchase requisitions)
-- Flow: raised -> hod_approved -> store_issued / purchase_pending
--       -> po_raised -> closed   (or rejected at any approval step)
-- ============================================================
CREATE TABLE IF NOT EXISTS purchase_indents (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    indent_no TEXT NOT NULL UNIQUE,              -- e.g. IND-2026-0001
    department TEXT NOT NULL,
    item_name TEXT NOT NULL,
    specification TEXT,
    quantity NUMERIC(12, 2) NOT NULL DEFAULT 1,
    estimated_cost NUMERIC(15, 2) NOT NULL DEFAULT 0,
    justification TEXT,
    budget_head TEXT,                            -- maps to department_budgets / CoA head
    status TEXT NOT NULL DEFAULT 'raised'
        CHECK (status IN ('raised', 'hod_approved', 'store_issued',
                          'purchase_pending', 'po_raised', 'closed', 'rejected')),
    raised_by TEXT,
    approved_by TEXT,
    created_at TIMESTAMP DEFAULT now(),
    updated_at TIMESTAMP DEFAULT now()
);

COMMENT ON TABLE purchase_indents IS 'Purchase requisition raised by a department; first step of Purchase-to-Pay.';
COMMENT ON COLUMN purchase_indents.indent_no IS 'Human readable unique indent number, generated by the app.';
COMMENT ON COLUMN purchase_indents.budget_head IS 'Budget head this indent will consume; checked against department_budgets.';

-- ============================================================
-- 2. PURCHASE ORDERS
-- vendor_id references vendors(id) created in migration 27.
-- vendor_name is kept denormalised so a PO stays readable even
-- for one-off / unregistered vendors.
-- ============================================================
CREATE TABLE IF NOT EXISTS purchase_orders (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    po_no TEXT NOT NULL UNIQUE,                  -- e.g. PO-2026-0001
    indent_id UUID REFERENCES purchase_indents(id) ON DELETE SET NULL,
    vendor_id UUID REFERENCES vendors(id) ON DELETE SET NULL,
    vendor_name TEXT,
    items JSONB NOT NULL DEFAULT '[]'::jsonb,    -- [{item_name, specification, quantity, rate, amount}]
    total_amount NUMERIC(15, 2) NOT NULL DEFAULT 0,
    gst_amount NUMERIC(15, 2) NOT NULL DEFAULT 0,
    delivery_date DATE,
    status TEXT NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'approved', 'sent', 'received',
                          'partially_received', 'cancelled')),
    approved_by TEXT,
    created_by TEXT,
    created_at TIMESTAMP DEFAULT now(),
    updated_at TIMESTAMP DEFAULT now()
);

COMMENT ON TABLE purchase_orders IS 'Purchase order issued to a vendor, optionally against a purchase_indents row.';
COMMENT ON COLUMN purchase_orders.items IS 'Line items as JSONB: item_name, specification, quantity, rate, amount.';

-- ============================================================
-- 3. GOODS RECEIPTS (GRN) — against a Purchase Order
-- Basis of the 3-way match: PO qty/rate vs GRN qty vs Vendor Bill.
-- ============================================================
CREATE TABLE IF NOT EXISTS goods_receipts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    po_id UUID NOT NULL REFERENCES purchase_orders(id) ON DELETE CASCADE,
    received_quantity NUMERIC(12, 2) NOT NULL DEFAULT 0,
    received_by TEXT,
    inspection_status TEXT NOT NULL DEFAULT 'accepted'
        CHECK (inspection_status IN ('accepted', 'partially_rejected', 'rejected')),
    remarks TEXT,
    received_at TIMESTAMP DEFAULT now(),
    created_at TIMESTAMP DEFAULT now()
);

COMMENT ON TABLE goods_receipts IS 'Goods Receipt Note: quantity actually received and inspected against a purchase order.';

-- ============================================================
-- 4. VENDOR BILLS — booked against a PO after GRN (3-way match)
-- payable_amount = bill_amount - tds_amount
-- ============================================================
CREATE TABLE IF NOT EXISTS vendor_bills (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    po_id UUID REFERENCES purchase_orders(id) ON DELETE SET NULL,
    vendor_name TEXT,
    bill_no TEXT,
    bill_amount NUMERIC(15, 2) NOT NULL DEFAULT 0,
    tds_amount NUMERIC(15, 2) NOT NULL DEFAULT 0,
    payable_amount NUMERIC(15, 2) NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'booked'
        CHECK (status IN ('booked', 'approved', 'paid', 'on_hold')),
    due_date DATE,
    paid_at TIMESTAMP,
    created_by TEXT,
    created_at TIMESTAMP DEFAULT now(),
    updated_at TIMESTAMP DEFAULT now()
);

COMMENT ON TABLE vendor_bills IS 'Vendor invoice booked against a PO; payment tracked till status = paid.';
COMMENT ON COLUMN vendor_bills.payable_amount IS 'Amount actually payable after TDS deduction (bill_amount - tds_amount).';

-- ============================================================
-- 5. RESEARCH / GOVERNMENT GRANTS (UGC, DST, DBT, AICTE...)
-- One row per sanctioned grant. Money NEVER mixes with the
-- general fund in reports: filter on this table + grant_expenses.
-- ============================================================
CREATE TABLE IF NOT EXISTS research_grants (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    grant_no TEXT NOT NULL UNIQUE,               -- sanction letter number
    title TEXT NOT NULL,
    funding_agency TEXT,                          -- UGC / DST / DBT / AICTE / ICSSR / State Govt...
    principal_investigator TEXT,                 -- PI name (faculty)
    sanctioned_amount NUMERIC(15, 2) NOT NULL DEFAULT 0,
    received_amount NUMERIC(15, 2) NOT NULL DEFAULT 0,
    utilized_amount NUMERIC(15, 2) NOT NULL DEFAULT 0,
    start_date DATE,
    end_date DATE,
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'closed', 'refunded')),
    created_by TEXT,
    created_at TIMESTAMP DEFAULT now(),
    updated_at TIMESTAMP DEFAULT now()
);

COMMENT ON TABLE research_grants IS 'Ring-fenced grant master: sanctioned vs received vs utilized per project.';
COMMENT ON COLUMN research_grants.grant_no IS 'Funding agency sanction letter number (unique).';

-- ============================================================
-- 6. GRANT EXPENSES — head-wise utilization of a grant
-- Utilization Certificate (UC) is generated from these rows.
-- ============================================================
CREATE TABLE IF NOT EXISTS grant_expenses (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    grant_id UUID NOT NULL REFERENCES research_grants(id) ON DELETE CASCADE,
    expense_head TEXT NOT NULL DEFAULT 'other'
        CHECK (expense_head IN ('equipment', 'manpower', 'consumables',
                                'travel', 'overheads', 'other')),
    description TEXT,
    amount NUMERIC(15, 2) NOT NULL DEFAULT 0,
    expense_date DATE DEFAULT CURRENT_DATE,
    voucher_no TEXT,
    created_by TEXT,
    created_at TIMESTAMP DEFAULT now()
);

COMMENT ON TABLE grant_expenses IS 'Head-wise expense booked against a research grant; feeds the Utilization Certificate.';

-- ============================================================
-- 7. INDEXES
-- ============================================================
CREATE INDEX IF NOT EXISTS idx_indents_status ON purchase_indents(status);
CREATE INDEX IF NOT EXISTS idx_indents_department ON purchase_indents(department);
CREATE INDEX IF NOT EXISTS idx_indents_created ON purchase_indents(created_at);
CREATE INDEX IF NOT EXISTS idx_po_indent ON purchase_orders(indent_id);
CREATE INDEX IF NOT EXISTS idx_po_vendor ON purchase_orders(vendor_id);
CREATE INDEX IF NOT EXISTS idx_po_status ON purchase_orders(status);
CREATE INDEX IF NOT EXISTS idx_grn_po ON goods_receipts(po_id);
CREATE INDEX IF NOT EXISTS idx_bills_po ON vendor_bills(po_id);
CREATE INDEX IF NOT EXISTS idx_bills_status ON vendor_bills(status);
CREATE INDEX IF NOT EXISTS idx_grants_status ON research_grants(status);
CREATE INDEX IF NOT EXISTS idx_grant_expenses_grant ON grant_expenses(grant_id);
CREATE INDEX IF NOT EXISTS idx_grant_expenses_head ON grant_expenses(grant_id, expense_head);

